"""Deterministic dummy LLM: parses the JSON payload of the last user message and returns a
canned but valid reply per agent role. Powers the whole pipeline offline (dev, CI, demo)."""
from __future__ import annotations

import json

from app.llm.base import LLMResponse

GENERATED_TEST_TEMPLATE = '''"""Generated by Airlock test-writer (dummy mode)."""
import {module}


def test_generated_edge_case():
    # Hypothesis for {target}: empty / boundary input crashes the changed code
    assert {module} is not None
'''


class DummyLLM:
    name = "dummy"

    def __init__(self) -> None:
        self.calls = 0

    async def chat(
        self,
        messages: list[dict],
        *,
        model: str = "dummy",
        temperature: float = 0.0,
        max_tokens: int = 1500,
        json_mode: bool = False,
    ) -> LLMResponse:
        self.calls += 1
        text = "\n".join(str(m.get("content", "")) for m in messages)
        payload = self._last_payload(messages)
        content = self._reply(text, payload)
        return LLMResponse(
            content=content,
            model="dummy",
            prompt_tokens=max(1, len(text) // 4),
            completion_tokens=max(1, len(content) // 4),
        )

    @staticmethod
    def _last_payload(messages: list[dict]) -> dict:
        for m in reversed(messages):
            if m.get("role") == "user":
                try:
                    data = json.loads(str(m["content"]))
                    return data if isinstance(data, dict) else {}
                except (json.JSONDecodeError, TypeError):
                    return {}
        return {}

    def _reply(self, text: str, p: dict) -> str:
        if "You plan a review." in text:
            language = p.get("language", "python")
            targets = [str(t) for t in p.get("risky_files", [])][:3]
            if language == "node":
                install, test = "npm ci", "npm test"
            else:
                install, test = "pip install -r requirements.txt", "python -m pytest -q"
            return json.dumps(
                {
                    "language": language,
                    "install_cmd": install,
                    "test_cmd": test,
                    "targets": targets,
                    "hypotheses": {t: f"suspicious behaviour possible in {t}" for t in targets},
                }
            )
        if "The setup command failed." in text:
            stderr = str(p.get("stderr_tail", ""))
            cmd = str(p.get("command", ""))
            if "requirements-wrong.txt" in stderr:
                return json.dumps(
                    {
                        "command": "pip install -r requirements.txt",
                        "explanation": "the referenced requirements file does not exist",
                    }
                )
            return json.dumps({"command": cmd, "explanation": "no better allowed command known"})
        if "Write ONE small" in text:
            target = str(p.get("target", "src/parser.py"))
            module = target.split("/")[-1].split(".")[0] or "package"
            return json.dumps(
                {
                    "path": "tests/test_airlock_generated.py",
                    "code": GENERATED_TEST_TEMPLATE.format(module=module, target=target),
                }
            )
        if "You are a security analyst." in text:
            cats = [str(f.get("category")) for f in p.get("findings", [])]
            ids = [str(f.get("id")) for f in p.get("findings", []) if f.get("id")]
            if "secret_access" in cats:
                intent = "data_theft"
            elif "network_attempt" in cats:
                intent = "backdoor"
            else:
                intent = "unclear"
            return json.dumps(
                {
                    "intent": intent,
                    "explanation": f"Based only on the cited evidence, the flagged code looks like {intent}.",
                    "cited_evidence": ids,
                    "confidence": 0.7,
                }
            )
        if "Write a summary" in text:
            label = str(p.get("verdict", {}).get("label", "unknown"))
            parts = [f"[{f.get('id')}] {f.get('title')}." for f in p.get("findings", []) if f.get("id")]
            summary = f"Verdict {label}. " + " ".join(parts)
            return json.dumps({"summary": summary.strip()})
        return json.dumps({"note": "dummy reply"})
